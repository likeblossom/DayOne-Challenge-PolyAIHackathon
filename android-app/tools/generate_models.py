"""Regenerate the eight typed Android form classes from the shared schema contract."""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'app/src/main/java/org/dayone/midwife/model'

def pascal(name):
    return ''.join(word.capitalize() for word in name.split('_'))

def leaf(spec):
    return {
        'double': ('Double', 'v -> ((Number) v).doubleValue()'),
        'integer': ('Integer', 'v -> ((Number) v).intValue()'),
        'boolean': ('Boolean', 'v -> (Boolean) v'),
        'date': ('java.time.LocalDate', 'v -> java.time.LocalDate.parse((String) v)'),
        'enum': ('String', 'v -> (String) v'),
        'string': ('String', 'v -> (String) v'),
    }[spec['type']]

def body(name, fields, form_id=None):
    declarations, assignments, nested = [], [], []
    for key, spec in fields.items():
        kind = spec['type']
        child = pascal(key) + 'Data'
        if kind == 'object':
            typ, expr = child, f'new {child}(object(data, "{key}"))'
            nested.append(body(child, spec['fields']))
        elif kind == 'array':
            item = spec['items']
            if item['type'] == 'object':
                typ, expr = f'java.util.List<{child}>', f'list(data, "{key}", {child}::new)'
                nested.append(body(child, item['fields']))
            else:
                scalar, mapper = leaf(item)
                typ = f'java.util.List<FieldValue<{scalar}>>'
                expr = f'list(data, "{key}", item -> new FieldValue<>(item, {mapper}))'
        else:
            scalar, mapper = leaf(spec)
            typ, expr = f'FieldValue<{scalar}>', f'field(data, "{key}", {mapper})'
        declarations.append(f'    public final {typ} {key};')
        assignments.append(f'        {key} = {expr};')
    head = f'public final class {name} extends PresetForm' if form_id else f'public static final class {name}'
    parent = f'        super("{form_id}", data);\n' if form_id else ''
    return head + ' {\n' + '\n'.join(declarations) + f'\n    public {name}(JSONObject data) {{\n' + parent + '\n'.join(assignments) + '\n    }\n' + '\n'.join(nested) + '\n}'

cases = []
for path in sorted((ROOT.parent / 'data/form_structures').glob('[0-9]*.schema.json')):
    schema = json.loads(path.read_text())
    name = pascal(schema['form_id']) + 'Form'
    code = '// Generated by tools/generate_models.py; edit the shared schema, then regenerate.\npackage org.dayone.midwife.model;\nimport org.json.JSONObject;\n\n'
    (OUT / f'{name}.java').write_text(code + body(name, schema['fields'], schema['form_id']) + '\n')
    shutil.copyfile(path, ROOT / 'app/src/main/assets/forms' / path.name)
    cases.append(f'            case "{schema["form_id"]}": return new {name}(fields);')
(OUT / 'FormTypes.java').write_text('''package org.dayone.midwife.model;
import org.json.JSONObject;
public final class FormTypes {
    private FormTypes() {}
    public static PresetForm create(String id, JSONObject fields) {
        switch (id) {
''' + '\n'.join(cases) + '''
            default: throw new IllegalArgumentException("Unsupported form: " + id);
        }
    }
}
''')
print(f'Generated {len(cases)} form classes and copied schema assets.')
